//! TypeScript types for the protocol, generated with ts-rs into `web/src/proto/generated`.

use super::sync::{Tree, read_tree, sync};
use crate::*;
use std::path::PathBuf;
use ts_rs::{Config, TS};

const INDEX: &str = "index.ts";

fn generated_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../web/src/proto/generated")
}

/// Exports the roots of the protocol; ts-rs follows the references to the other types.
fn export(cfg: &Config) {
    ClientFrame::export_all(cfg).expect("ClientFrame");
    Request::export_all(cfg).expect("Request");
    ServerFrame::export_all(cfg).expect("ServerFrame");
    SessionSnapshot::export_all(cfg).expect("SessionSnapshot");
    ServerConfigInfo::export_all(cfg).expect("ServerConfigInfo");
    McpServerStatus::export_all(cfg).expect("McpServerStatus");
    NamedImage::export_all(cfg).expect("NamedImage");
    InstanceInfo::export_all(cfg).expect("InstanceInfo");
}

/// `index.ts`: one re-export per generated type, plus the protocol version.
fn index(files: &Tree) -> String {
    let mut out = String::from(
        "// Generated by `REF_UPDATE_FIXTURES=1 cargo test -p ref-proto`. Do not edit.\n",
    );
    for path in files.keys() {
        let module = path.trim_end_matches(".ts");
        let name = module.rsplit('/').next().expect("module name");
        out.push_str(&format!("export type {{ {name} }} from \"./{module}\";\n"));
    }
    out.push_str(&format!(
        "\nexport const PROTOCOL_VERSION = {PROTOCOL_VERSION};\n"
    ));
    out
}

fn generate() -> Tree {
    let tmp = std::env::temp_dir().join(format!("ref-proto-ts-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&tmp);
    // `bigint` is ts-rs' default for 64-bit integers; JSON numbers parse as `number`.
    export(&Config::new().with_large_int("number").with_out_dir(&tmp));
    let mut files = read_tree(&tmp);
    std::fs::remove_dir_all(&tmp).expect("remove temp dir");
    let index = index(&files);
    files.insert(INDEX.into(), index);
    files
}

#[test]
fn typescript_bindings_are_up_to_date() {
    sync(&generated_dir(), &generate(), "TypeScript types");
}

/// Variant tags of a tagged enum, read from its generated declaration (`"op": "hello"`).
pub fn declared_variants<T: TS>(tag: &str) -> Vec<String> {
    let cfg = Config::new();
    let marker = format!("\"{tag}\": \"");
    let decl = T::decl(&cfg);
    decl.split(&marker)
        .skip(1)
        .map(|rest| rest.split('"').next().expect("closing quote").to_string())
        .collect()
}

/// String literals of a plain enum declaration (`"a" | "b"`).
pub fn declared_literals<T: TS>() -> Vec<String> {
    let decl = T::decl(&Config::new());
    decl.split('"')
        .skip(1)
        .step_by(2)
        .map(str::to_string)
        .collect()
}
