// Generates the WebUI's CSS variables and TS constants from the GUI's QML singletons.
// gui/src/app/Theme.qml and Motion.qml are the single source; so are the component properties
// listed in COMPONENT_PROPERTIES below.
//
//   node scripts/gen-theme.ts           write src/theme/generated/*
//   node scripts/gen-theme.ts --check   fail if the files on disk are not what would be written

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { easingNameFromQml, outElastic, plainEasings } from '../src/motion/easing.ts'
import type { EasingFn } from '../src/motion/easing.ts'
import { linearPoints, toCssLinear } from '../src/motion/linearCss.ts'
import { cssColor, findProperty, parseProperties, parseValue } from './qmlProperties.ts'
import type { QmlProperty } from './qmlProperties.ts'

type Unit = 'px' | 'ms' | '' // '' = unitless

const WEB_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const QML_DIR = join(WEB_ROOT, '..', 'gui', 'src', 'app')
const OUT_DIR = join(WEB_ROOT, 'src', 'theme', 'generated')

// Theme.qml properties that are not literals; the web side has its own value.
const THEME_SKIPPED = ['monoFamily']
const THEME_STRINGS = ['syntaxTheme'] // string properties, TS only
// Theme.qml numbers that are not pixels.
const METRIC_UNITLESS = [
  'paletteTopRatio',
  'dialogMaxHeightRatio',
  'sidebarMinRunningRows',
  'paletteMaxRows',
  'toastMax',
  'staleOpacity',
]

const MOTION_UNITS: Record<string, Unit> = {
  quick: 'ms',
  standard: 'ms',
  slow: 'ms',
  pulse: 'ms',
  calmPulse: 'ms',
  enterDrop: 'px',
  followLag: 'ms',
  chaseSnap: 'px',
  interruptWindow: 'ms',
  dialogDrop: 'px',
  popScale: '',
  tileEnterScale: '',
  tileExitScale: '',
  toastSlide: 'px',
  toastInfoMs: 'ms',
  toastWarnMs: 'ms',
  toastErrorMs: 'ms',
}

// Component constants that the web side needs. Only these are read; each must be a literal.
// Values derived from other properties (`width * 0.3`) are written by hand in the .vue file.
const COMPONENT_PROPERTIES: Record<string, Record<string, Unit>> = {
  Flourish: {
    gatheredScale: '',
    entryScale: '',
    springAmplitude: '',
    entrySpringAmplitude: '',
    springPeriod: '',
    springDuration: 'ms',
  },
  Composer: { padding: 'px', maxInputHeight: 'px' },
  ErrorBlock: { verticalPadding: 'px', horizontalPadding: 'px', spreadSpeed: '' },
  UserBlock: { horizontalPadding: 'px', verticalPadding: 'px' },
}

// Curves written out as `linear()`: the ones QML uses by name. `linear` is a CSS keyword already.
const CSS_EASINGS = ['inQuad', 'inCubic', 'inOutSine', 'outExpo', 'outBack'] as const

const HEADER = 'Generated by scripts/gen-theme.ts from gui/src/app/*.qml. Do not edit; run `pnpm gen`.'

function kebab(name: string): string {
  return name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)
}

function lowerFirst(name: string): string {
  return name.charAt(0).toLowerCase() + name.slice(1)
}

function loadQml(file: string): { properties: QmlProperty[]; where: string } {
  const path = join(QML_DIR, file)
  return { properties: parseProperties(readFileSync(path, 'utf8')), where: relative(WEB_ROOT, path) }
}

function cssNumber(value: number, unit: Unit): string {
  return value === 0 || unit === '' ? String(value) : `${value}${unit}`
}

function tsObject(entries: [string, string][], indent: string): string {
  return entries.map(([key, value]) => `${indent}${key}: ${value},`).join('\n')
}

function tsString(value: string): string {
  return `'${value}'`
}

interface Theme {
  colors: { light: [string, string][]; dark: [string, string][] }
  metrics: [string, number][]
  strings: [string, { light: string; dark: string }][]
  lists: [string, string[]][] // arrays of color names
}

function readTheme(): Theme {
  const { properties, where } = loadQml('Theme.qml')
  const theme: Theme = { colors: { light: [], dark: [] }, metrics: [], strings: [], lists: [] }

  for (const property of properties.filter((p) => p.readonly && !THEME_SKIPPED.includes(p.name))) {
    const value = parseValue(property, where)
    if (property.type === 'color' && value.kind === 'themed') {
      theme.colors.dark.push([property.name, cssColor(String(value.dark))])
      theme.colors.light.push([property.name, cssColor(String(value.light))])
    } else if (THEME_STRINGS.includes(property.name) && value.kind === 'themed') {
      theme.strings.push([property.name, { light: String(value.light), dark: String(value.dark) }])
    } else if (value.kind === 'list') {
      theme.lists.push([property.name, value.names])
    } else if (value.kind === 'number') {
      theme.metrics.push([property.name, value.value])
    } else {
      throw new Error(
        `${where}:${property.line}: unexpected form of "${property.name}"; add it to the generator`,
      )
    }
  }
  for (const [name, names] of theme.lists) {
    const known = theme.colors.light.map(([colorName]) => colorName)
    const missing = names.filter((entry) => !known.includes(entry))
    if (missing.length > 0) throw new Error(`${where}: "${name}" lists unknown colors: ${missing.join(', ')}`)
  }
  return theme
}

interface Motion {
  numbers: [string, number, Unit][]
  easings: [string, string][] // property -> easing name
}

function readMotion(): Motion {
  const { properties, where } = loadQml('Motion.qml')
  const motion: Motion = { numbers: [], easings: [] }

  for (const property of properties.filter((p) => p.readonly)) {
    const value = parseValue(property, where)
    if (value.kind === 'easing') {
      motion.easings.push([property.name, easingNameFromQml(value.name)])
      continue
    }
    const unit = MOTION_UNITS[property.name]
    if (value.kind !== 'number' || unit === undefined) {
      throw new Error(`${where}:${property.line}: add "${property.name}" to MOTION_UNITS or make it a number`)
    }
    motion.numbers.push([property.name, value.value, unit])
  }
  return motion
}

type ComponentValues = Record<string, [string, number, Unit][]>

function readComponents(): ComponentValues {
  const result: ComponentValues = {}
  for (const [component, wanted] of Object.entries(COMPONENT_PROPERTIES)) {
    const { properties, where } = loadQml(`${component}.qml`)
    result[lowerFirst(component)] = Object.entries(wanted).map(([name, unit]) => {
      const property = findProperty(properties, name, where)
      const value = parseValue(property, where)
      if (value.kind !== 'number') throw new Error(`${where}:${property.line}: "${name}" must be a number`)
      return [name, value.value, unit]
    })
  }
  return result
}

function cssEasing(fn: EasingFn): string {
  return toCssLinear(linearPoints(fn))
}

function flourishValue(components: ComponentValues, name: string): number {
  const entry = components['flourish']?.find(([n]) => n === name)
  if (!entry) throw new Error(`Flourish.${name} is needed for the spring curves`)
  return entry[1]
}

function buildCss(theme: Theme, motion: Motion, components: ComponentValues): string {
  const colorBlock = (colors: [string, string][]) =>
    colors.map(([name, value]) => `  --${kebab(name)}: ${value};`).join('\n')

  const metrics = theme.metrics.map(
    ([name, value]) => `  --${kebab(name)}: ${cssNumber(value, METRIC_UNITLESS.includes(name) ? '' : 'px')};`,
  )
  const lists = theme.lists.flatMap(([name, names]) =>
    names.map((entry, index) => `  --${kebab(name)}-${index}: var(--${kebab(entry)});`),
  )
  const motionNumbers = motion.numbers.map(
    ([name, value, unit]) => `  --motion-${kebab(name)}: ${cssNumber(value, unit)};`,
  )
  const motionEasings = motion.easings.map(([name, easing]) => {
    if (!CSS_EASINGS.includes(easing as (typeof CSS_EASINGS)[number])) {
      throw new Error(`Motion.${name} uses ${easing}, which has no CSS curve; add it to CSS_EASINGS`)
    }
    return `  --motion-${kebab(name)}: var(--easing-${kebab(easing)});`
  })
  const plain = CSS_EASINGS.map((name) => `  --easing-${kebab(name)}: ${cssEasing(plainEasings[name])};`)
  const springs = [
    ['spring', 'springAmplitude'],
    ['entry-spring', 'entrySpringAmplitude'],
  ].map(([name, amplitude]) => {
    const spring = outElastic(
      flourishValue(components, amplitude!),
      flourishValue(components, 'springPeriod'),
    )
    return `  --easing-flourish-${name}: ${cssEasing(spring)};`
  })
  const componentVars = Object.entries(components).flatMap(([component, values]) =>
    values.map(([name, value, unit]) => `  --${kebab(component)}-${kebab(name)}: ${cssNumber(value, unit)};`),
  )

  return [
    `/* ${HEADER} */`,
    ':root {',
    '  color-scheme: light;',
    colorBlock(theme.colors.light),
    ...metrics,
    ...lists,
    ...motionNumbers,
    ...motionEasings,
    ...plain,
    ...springs,
    ...componentVars,
    '}',
    '',
    ":root[data-theme='dark'] {",
    '  color-scheme: dark;',
    colorBlock(theme.colors.dark),
    '}',
    '',
  ].join('\n')
}

function buildThemeTs(theme: Theme): string {
  const colors = (list: [string, string][]) =>
    tsObject(
      list.map(([n, v]) => [n, tsString(v)]),
      '    ',
    )
  const strings = theme.strings.map(
    ([name, v]) => `  ${name}: { light: ${tsString(v.light)}, dark: ${tsString(v.dark)} },`,
  )
  return [
    `// ${HEADER}`,
    '',
    'export const colors = {',
    '  light: {',
    colors(theme.colors.light),
    '  },',
    '  dark: {',
    colors(theme.colors.dark),
    '  },',
    '} as const',
    '',
    'export type ColorName = keyof typeof colors.light',
    '',
    '// px, except the ratios and counts in METRIC_UNITLESS of scripts/gen-theme.ts',
    'export const metrics = {',
    tsObject(
      theme.metrics.map(([n, v]) => [n, String(v)]),
      '  ',
    ),
    '} as const',
    '',
    'export const themedStrings = {',
    ...strings,
    '} as const',
    '',
    ...theme.lists.flatMap(([name, names]) => [
      `export const ${name} = [${names.map(tsString).join(', ')}] as const satisfies readonly ColorName[]`,
      '',
    ]),
  ].join('\n')
}

function buildMotionTs(motion: Motion): string {
  return [
    `// ${HEADER}`,
    '',
    "import type { EasingName } from '../../motion/easing.ts'",
    '',
    '// ms, except the px distances and unitless scales listed in MOTION_UNITS of scripts/gen-theme.ts',
    'export const motion = {',
    tsObject(
      motion.numbers.map(([n, v]) => [n, String(v)]),
      '  ',
    ),
    '} as const',
    '',
    'export const motionEasing = {',
    tsObject(
      motion.easings.map(([n, e]) => [n, tsString(e)]),
      '  ',
    ),
    '} as const satisfies Record<string, EasingName>',
    '',
  ].join('\n')
}

function buildComponentsTs(components: ComponentValues): string {
  const groups = Object.entries(components).flatMap(([component, values]) => [
    `  ${component}: {`,
    tsObject(
      values.map(([n, v, unit]) => [n, `${v} /* ${unit || 'unitless'} */`]),
      '    ',
    ),
    '  },',
  ])
  return [`// ${HEADER}`, '', 'export const components = {', ...groups, '} as const', ''].join('\n')
}

function generate(): Map<string, string> {
  const theme = readTheme()
  const motion = readMotion()
  const components = readComponents()
  return new Map([
    ['theme.css', buildCss(theme, motion, components)],
    ['theme.ts', buildThemeTs(theme)],
    ['motion.ts', buildMotionTs(motion)],
    ['components.ts', buildComponentsTs(components)],
  ])
}

function check(files: Map<string, string>): boolean {
  const stale = [...files].filter(([name, content]) => {
    const path = join(OUT_DIR, name)
    return !existsSync(path) || readFileSync(path, 'utf8') !== content
  })
  for (const [name] of stale) console.error(`stale: src/theme/generated/${name}`)
  if (stale.length > 0) console.error('Run `pnpm gen` in web/ and commit the result.')
  return stale.length === 0
}

function write(files: Map<string, string>): void {
  mkdirSync(OUT_DIR, { recursive: true })
  for (const [name, content] of files) writeFileSync(join(OUT_DIR, name), content)
}

const files = generate()
if (process.argv.includes('--check')) {
  process.exit(check(files) ? 0 : 1)
}
write(files)
