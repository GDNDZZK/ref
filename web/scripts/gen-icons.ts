// Inlines assets/icons/*.svg into src/icons/generated/icons.ts, so icons are typed names and
// need no extra request (the CSP allows no inline scripts, but inline SVG markup is fine).
//
//   node scripts/gen-icons.ts           write src/icons/generated/icons.ts
//   node scripts/gen-icons.ts --check   fail if the file on disk is not what would be written

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const WEB_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const ICON_DIR = join(WEB_ROOT, '..', 'assets', 'icons')
const OUT_FILE = join(WEB_ROOT, 'src', 'icons', 'generated', 'icons.ts')
const FILE_PATTERN = /^([a-z0-9]+(?:-[a-z0-9]+)*-(?:16|20))\.svg$/

function readIcons(): [string, string][] {
  const names = readdirSync(ICON_DIR).filter((file) => file !== 'INDEX.md' && !file.startsWith('preview'))
  return names.sort().map((file) => {
    const match = FILE_PATTERN.exec(file)
    if (!match?.[1]) throw new Error(`assets/icons/${file} is not named <name>-16.svg or <name>-20.svg`)
    const markup = readFileSync(join(ICON_DIR, file), 'utf8')
      .split('\n')
      .map((line) => line.trim())
      .join('')
    if (!markup.includes('currentColor')) throw new Error(`assets/icons/${file} does not use currentColor`)
    return [match[1], markup]
  })
}

function build(icons: [string, string][]): string {
  const rows = icons.map(([key, markup]) => `  '${key}': ${JSON.stringify(markup)},`)
  return [
    '// Generated by scripts/gen-icons.ts from assets/icons/*.svg. Do not edit; run `pnpm gen`.',
    '',
    'export const icons = {',
    ...rows,
    '} as const',
    '',
    "export type IconKey = keyof typeof icons // '<name>-16' or '<name>-20'",
    '',
  ].join('\n')
}

const content = build(readIcons())
if (process.argv.includes('--check')) {
  const fresh = existsSync(OUT_FILE) && readFileSync(OUT_FILE, 'utf8') === content
  if (!fresh)
    console.error('stale: src/icons/generated/icons.ts\nRun `pnpm gen` in web/ and commit the result.')
  process.exit(fresh ? 0 : 1)
}
mkdirSync(dirname(OUT_FILE), { recursive: true })
writeFileSync(OUT_FILE, content)
