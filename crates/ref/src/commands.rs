//! Slash commands registry.

pub struct Cmd {
    pub name: &'static str,
    pub aliases: &'static [&'static str],
    pub desc: &'static str,
    pub key: &'static str,
    /// Takes an argument (completion inserts `/name ` instead of running).
    pub arg: bool,
}

